const cache = new Map();
// returns 5 column masks (bit r = row r lit, r=0 top)
export function glyph(ch) {
  if (cache.has(ch)) return cache.get(ch);
  const rows = (G[ch] || G['?']).split(' ');
  const cols = [0, 0, 0, 0, 0];
  rows.forEach((row, r) => { for (let c = 0; c < 5; c++) if (row[c] === '1') cols[c] |= 1 << r; });
  cache.set(ch, cols);
  return cols;
}
